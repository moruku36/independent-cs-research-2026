## 2. 概要 (Executive Summary)
AI活用の最前線にあるAnthropic社内の人事データ、生産量指標、およびAIエージェントの稼働テレメトリを統合分析し、AIエージェントの急速な浸透が組織構造、採用、業務プロセスに与える影響を実証したレポート。
2026年3月に社内AIエージェントの総稼働時間が人間の労働時間を初めて上回り、同年8月には人間が指示した対話型エージェントの稼働時間が従業員の推定労働時間の**6倍**（研究部門では**19倍**）に達した。これに伴い、個人のアウトプット（コードコミット数、営業成約数、法務契約処理数など）は急増したが、その反面「人間の注意力（Human Attention）」が最大のボトルネックとなり、業務の中心が実務からエージェント群を監視・制御する「メタワーク（Meta-work）」へと移行している実態を明らかにしている。

